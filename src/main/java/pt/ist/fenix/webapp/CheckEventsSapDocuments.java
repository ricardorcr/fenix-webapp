    private String hasMissingDocs(final Event event) {
        final boolean txNotSent = event.getNonAdjustingTransactions().stream()
                .anyMatch(tx -> tx.getSapRequestSet().isEmpty());
        final boolean exemptionNotSent = event.getExemptionsSet().stream()
                .anyMatch(this::hasNotSapRequest);
        final boolean hasOpenInvoice = event.getSapRequestSet().stream()
                .filter(sr -> sr.getRequestType() == SapRequestType.INVOICE)
                .anyMatch(sr -> sr.openInvoiceValue().isPositive());
//        taskLog("TXs %s%n", txNotSent);
//        taskLog("Exemptions %s%n", exemptionNotSent);
//        taskLog("OpenInvoice %s%n", hasOpenInvoice);
        return txNotSent || exemptionNotSent || hasOpenInvoice ? "Sim" : "Não";
    }

    private boolean hasNotSapRequest(final Exemption exemption) {
        return !exemption.getEvent().getSapRequestSet().stream()
                .filter(sr -> sr.getRequestType() == SapRequestType.CREDIT)
                .filter(SapRequest::getIntegrated)
                .filter(sr -> exemption.getExternalId().equals(sr.getCreditId()))
                .findAny().isPresent();
    }
